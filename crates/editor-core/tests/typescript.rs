//! The TypeScript boundary types, generated from the schema (task 2.2).
//!
//! `cargo test --features typescript` fails when the checked-in file is stale;
//! `UPDATE_ENGINE_TYPES=1 cargo test --features typescript` rewrites it.
#![cfg(feature = "typescript")]

use std::path::Path;

use maleo_editor_core::captions::*;
use maleo_editor_core::{Clip, ClipType, EditScope, EditorCommand, EditorDoc};
use ts_rs::{Config, TS};

const GENERATED: &str = "../../packages/shared/src/editor/engine-types.generated.ts";

fn generated() -> String {
    let cfg = Config::new();
    let decls = [
        CaptionTimingOrigin::decl(&cfg),
        CaptionCueWord::decl(&cfg),
        CaptionSourceBinding::decl(&cfg),
        CaptionProtection::decl(&cfg),
        CaptionProvenance::decl(&cfg),
        CaptionStatus::decl(&cfg),
        CaptionCue::decl(&cfg),
        CaptionDeletedRange::decl(&cfg),
        CaptionSet::decl(&cfg),
        ClipType::decl(&cfg),
        Clip::decl(&cfg),
        EditorDoc::decl(&cfg),
        EditScope::decl(&cfg),
        EditorCommand::decl(&cfg),
    ];
    let body: Vec<String> = decls.iter().map(|decl| format!("export {decl}\n")).collect();
    format!(
        "/* GENERATED by crates/editor-core/tests/typescript.rs from the Rust schema. Do not edit.\n * Regenerate: UPDATE_ENGINE_TYPES=1 cargo test --features typescript\n * Checked against the hand-written types by engine-types.check.ts. */\n{}",
        body.join("\n")
    )
}

#[test]
fn generated_typescript_is_current() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(GENERATED);
    let expected = generated();
    if std::env::var_os("UPDATE_ENGINE_TYPES").is_some() {
        std::fs::write(&path, &expected).expect("writes generated types");
    }
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    assert_eq!(current, expected, "{} is stale: run UPDATE_ENGINE_TYPES=1 cargo test --features typescript", path.display());
}
