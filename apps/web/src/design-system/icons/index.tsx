/* The icon size scale. Four steps for interface chrome, two for state
 * illustration (empty states, status orbs). Call sites name a step —
 * `Ic.check(ICON.sm)` — and check-layers rejects a numeric literal outside this
 * module, so a 13px or 15px glyph cannot reappear because it looked right. */
