/* Maleo — the single icon registry, drawn by Lucide (lucide-react, ISC).
 *
 * One convention: every glyph is `(size?: number) => JSX.Element`, so a call
 * site reads `Ic.check(14)` and never names the library. This module is the
 * only importer of lucide-react (check-layers enforces it), so the set can be
 * swapped or a glyph redrawn in one place. Glyphs inherit `currentColor`, keep
 * Lucide's stroke, and are decorative: an icon-only control names itself with
 * `aria-label` (IconButton requires one).
 *
 * The names are the app's vocabulary, not Lucide's: `Ic.regen` is whatever
 * "regenerate" looks like this year. Each glyph keeps the default size its call
 * sites were written against. The tail of the list holds the glyphs that used
 * to be drawn inside feature files (undo/redo, skip, aspect shapes, track
 * toggles, transitions, the spinner); a variant that was a flag on a local
 * glyph (redo, eye-off, unlocked, muted) is its own name here. */
